"""Export the model tables: results/params.md and the generated C source and header.

Single source of truth (the spec, S1): results/params.csv holds the axes and the seven tables
(OCV, dOCV/dSoC, R0, R1, tau1, R2, tau2) on the 101-point SoC grid, results/fit_levels.csv holds
the HPPC level fits they were resampled from, and results/ocv_correction.csv holds the correction of the
OCV at each HPPC rest point. All three are written by python/fit_all.py, which calls export_params()
after it has written them. This script turns them into

  results/params.md       tables for the reader: the fit at each HPPC level, C = tau / R,
                          the fit RMSE, the OCV valid SoC range, the OCV fallback flag and the
                          OCV correction at the rest points
  c/include/ekf_params.h  the two size defines, Q_ref (Q_REF_AH of constants.py), extern
                          declarations of the nine arrays, the ekf_params_t struct of pointers
                          to them and its default instance
  c/src/ekf_params.c      the arrays as const ekf_real_t, one row per temperature, and
                          ekf_params_default pointing at them

so Python and C look up the same numbers. Nothing is typed by hand and the output is deterministic.

Run from the repo root:  .venv/bin/python python/export_params.py
"""

import numpy as np
import pandas as pd

from ekfsoc.constants import Q_REF_AH, REPO_DIR, SOC_GRID, T_GRID_DEGC
from ekfsoc.model import Params


PARAMS_CSV = REPO_DIR / "results" / "params.csv"
LEVELS_CSV = REPO_DIR / "results" / "fit_levels.csv"
OCV_CORRECTION_CSV = REPO_DIR / "results" / "ocv_correction.csv"
PARAMS_MD = REPO_DIR / "results" / "params.md"
C_SOURCE = REPO_DIR / "c" / "src" / "ekf_params.c"
C_HEADER = REPO_DIR / "c" / "include" / "ekf_params.h"

# Significant digits of a literal in the generated C file, and literals per line.
C_DIGITS = 7
C_VALUES_PER_LINE = 4

GENERATED_NOTE = "generated by python/export_params.py from results/params.csv, do not edit"

# The seven tables as C arrays: (attribute of Params, C name, what the table holds).
C_TABLES = (
    ("ocv", "ekf_ocv_v", "OCV in V"),
    ("docv", "ekf_docv_v_per_soc", "dOCV/dSoC in V per unit SoC"),
    ("r0", "ekf_r0_ohm", "R0 in Ohm"),
    ("r1", "ekf_r1_ohm", "R1 in Ohm"),
    ("tau1", "ekf_tau1_s", "tau1 in s"),
    ("r2", "ekf_r2_ohm", "R2 in Ohm"),
    ("tau2", "ekf_tau2_s", "tau2 in s"),
)


def write_text(path, text):
    """Write `text` to `path`, creating the folder; newline="\\n" so the bytes are the same on every platform."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, newline="\n")


# --- C files -------------------------------------------------------------------------------------


def c_literal(value, digits=C_DIGITS):
    """Return `value` as a C literal in scientific notation with `digits` significant digits, e.g. EKF_R(7.000000e-02).

    EKF_R (c/include/ekf_types.h) appends f in the float build and nothing in the double build, so
    one generated file compiles clean under -Wdouble-promotion in both. Scientific notation always
    has a point, so the pasted text is a floating literal ('40f' would not be one). params.csv holds
    6 significant digits, so the default 7 lose nothing; the C test vectors use 17, which give back
    the same double. A value that is not finite has no literal: ValueError.
    """
    if not np.isfinite(value):
        raise ValueError(f"cannot write {value} as a C literal")
    return f"EKF_R({value:.{digits - 1}e})"


def c_values_lines(values, indent):
    """Return the literals of one 1-D array as indented lines of C_VALUES_PER_LINE values, ending in commas."""
    return [
        indent + ", ".join(c_literal(value) for value in values[start : start + C_VALUES_PER_LINE]) + ","
        for start in range(0, len(values), C_VALUES_PER_LINE)
    ]


def c_array(declaration, comment, body):
    """Return the definition of one const ekf_real_t array, after a blank line and a comment."""
    return ["", f"/* {comment} */", f"const ekf_real_t {declaration} = {{", *body, "};"]


def header_text(params):
    """Return the text of c/include/ekf_params.h: the size defines, Q_ref, the nine arrays and the ekf_params_t struct."""
    lines = [
        f"/* {GENERATED_NOTE}",
        " *",
        " * The model tables of docs/model.md on the two axes of C15. Table row j is the temperature",
        " * ekf_t_grid_degc[j] (descending, 40 down to -20 degC) and column m is the SoC ekf_soc_grid[m]",
        " * (ascending, 0 to 1). Read a table with the bilinear, clamped lookup of Eq. 4.",
        " */",
        "#ifndef EKF_PARAMS_H",
        "#define EKF_PARAMS_H",
        "",
        '#include "ekf_types.h"',
        "",
        f"#define EKF_N_T {len(params.t_grid)}",
        f"#define EKF_N_SOC {len(params.soc_grid)}",
        f"#define EKF_Q_REF_AH {c_literal(Q_REF_AH)}  /* Q_ref in Ah, Q_REF_AH of python/ekfsoc/constants.py (docs/model.md C4) */",
        "",
        "extern const ekf_real_t ekf_t_grid_degc[EKF_N_T];  /* temperature axis in degC */",
        "extern const ekf_real_t ekf_soc_grid[EKF_N_SOC];  /* SoC axis as a fraction */",
    ]
    lines += [f"extern const ekf_real_t {c_name}[EKF_N_T][EKF_N_SOC];  /* {meaning} */"
              for _, c_name, meaning in C_TABLES]
    lines += [
        "",
        "/* One set of model tables. Each table pointer is row-major: entry [j][m] is at j * EKF_N_SOC + m. */",
        "typedef struct {",
        "    const ekf_real_t *t_grid;  /* temperature axis in degC, EKF_N_T nodes */",
        "    const ekf_real_t *soc_grid;  /* SoC axis as a fraction, EKF_N_SOC nodes */",
    ]
    lines += [f"    const ekf_real_t *{attribute};  /* {meaning} */" for attribute, _, meaning in C_TABLES]
    lines += [
        "} ekf_params_t;",
        "",
        "extern const ekf_params_t ekf_params_default;  /* the arrays above */",
        "",
        "#endif /* EKF_PARAMS_H */",
    ]
    return "\n".join(lines) + "\n"


def source_text(params):
    """Return the text of c/src/ekf_params.c: the two axes and the seven tables as const ekf_real_t arrays, and ekf_params_default."""
    lines = [f"/* {GENERATED_NOTE} */", "", '#include "ekf_params.h"']
    lines += c_array("ekf_t_grid_degc[EKF_N_T]", "temperature axis in degC, one table row each",
                     c_values_lines(params.t_grid, "    "))
    lines += c_array("ekf_soc_grid[EKF_N_SOC]", "SoC axis as a fraction, one table column each",
                     c_values_lines(params.soc_grid, "    "))
    for attribute, c_name, meaning in C_TABLES:
        body = []
        for temp, row in zip(params.t_grid, getattr(params, attribute)):
            body += [f"    {{ /* T = {temp:g} degC */", *c_values_lines(row, "        "), "    },"]
        lines += c_array(f"{c_name}[EKF_N_T][EKF_N_SOC]", meaning, body)
    lines += [
        "",
        "/* the arrays above as one parameter set */",
        "const ekf_params_t ekf_params_default = {",
        "    .t_grid = ekf_t_grid_degc,",
        "    .soc_grid = ekf_soc_grid,",
    ]
    lines += [f"    .{attribute} = &{c_name}[0][0]," for attribute, c_name, _ in C_TABLES]
    lines += ["};"]
    return "\n".join(lines) + "\n"


def write_c_files(params, c_path, h_path):
    """Write the C source and header for `params`; refuse axes that are not the project grids."""
    if not np.allclose(params.t_grid, T_GRID_DEGC) or not np.allclose(params.soc_grid, SOC_GRID, rtol=0.0, atol=1e-6):
        raise ValueError("params axes are not the project grids (T_GRID_DEGC, SOC_GRID)")
    write_text(c_path, source_text(params))
    write_text(h_path, header_text(params))


# --- results/params.md ---------------------------------------------------------------------------


def fmt(value, digits=4):
    """Return `value` with `digits` significant digits and no exponent, or 'n/a' for a missing value.

    A failed fit has no value (an empty cell in fit_levels.csv, NaN once read), and so has the
    R2 and tau2 of the last HPPC level, which has no 1 h rest.
    """
    if not np.isfinite(value):
        return "n/a"
    return np.format_float_positional(float(value), precision=digits, unique=False, fractional=False, trim="-")


def fmt_int(value):
    """Return a count as text, or 'n/a' when it is missing."""
    return str(int(value)) if np.isfinite(value) else "n/a"


def capacitance(tau, resistance):
    """Return C = tau / R in F, or NaN when R is missing or not above zero.

    A failed fit leaves R missing (NaN), and a fit that ends at a zero resistance has no finite C;
    neither may stop the export, and both print as 'n/a'.
    """
    if not resistance > 0.0:
        return float("nan")
    return tau / resistance


def md_row(cells):
    """Return one markdown table row from a list of text cells."""
    return "| " + " | ".join(cells) + " |"


def md_table(header, rows):
    """Return the lines of a markdown table: `header` is a list of column titles and `rows` a list of lists of text."""
    return [md_row(header), "|" + "---|" * len(header)] + [md_row(row) for row in rows]


def ocv_valid_first_index(ocv_row):
    """Return the index of the first grid SoC where the OCV is measured, or None if the whole row is flat.

    Below the lowest SoC the C/20 discharge reached, the OCV table holds one value
    (docs/decisions.md 1.1), so the row starts with a run of equal values. The first grid SoC where
    the OCV changes from the node before it is the first one inside the measured range.
    A row that does not start with such a run (the 25 degC discharge reaches SoC 0) is valid from index 0.
    """
    changes = np.flatnonzero(ocv_row[1:] != ocv_row[:-1])
    if len(changes) == 0:
        return None
    return 0 if changes[0] == 0 else changes[0] + 1


def ocv_lines(params):
    """Return the lines of the section on the OCV: how it is made, the fallback flag and the valid range per temperature."""
    # The spec copies the 25 degC OCV row to every temperature when a cold curve is not monotone.
    fallback_used = bool(np.all(params.ocv == params.ocv[0]))
    rows = []
    for temp, ocv_row in zip(params.t_grid, params.ocv):
        first = ocv_valid_first_index(ocv_row)
        if first is None:
            rows.append([f"{temp:g}", "n/a", str(len(ocv_row))])
        else:
            rows.append([f"{temp:g}", f"{100.0 * params.soc_grid[first]:.1f}", str(first)])
    lines = [
        "## OCV",
        "",
        "OCV comes from the C/20 discharge half, corrected onto the HPPC rest voltages (docs/decisions.md 1.1). "
        "Below the lowest SoC a discharge reached, the table holds its last value, so the OCV is measured from "
        "the first grid SoC where it changes from the node before it (from 0 when nothing is held).",
        "",
        f"OCV fallback (the 25 degC curve used at every temperature): {'yes' if fallback_used else 'no'}.",
        "",
    ]
    return lines + md_table(["T (degC)", "OCV valid from SoC (%)", "grid points held below"], rows)


def ocv_correction_lines(correction_df):
    """Return the lines of the section on the OCV correction: the rule, then one table row per rest point."""
    rows = [
        [f"{row.T_degC:g}", fmt(100.0 * row.soc), fmt(row.v_rest_V, 5), fmt(row.v_c20_V, 5), fmt(row.delta_mV)]
        for row in correction_df.itertuples()
    ]
    lines = [
        "## OCV correction from the HPPC rest voltages",
        "",
        "At each rest point (the last row of every 1 h rest after a move, and the last row before the first "
        "discharge pulse of level 1) delta = V rest - V C/20 at the same SoC, and a PCHIP through the deltas, "
        "held flat beyond the first and last point, is added to the C/20 curve (docs/decisions.md 1.1).",
        "",
    ]
    return lines + md_table(["T (degC)", "SoC (%)", "V rest (V)", "V C/20 (V)", "delta (mV)"], rows)


def fast_branch_row(level):
    """Table row of the fast branch for one fit_levels.csv row: R0, R1, tau1 and C1 = tau1 / R1 at the SoC of the pulses."""
    return [
        fmt_int(level.level),
        fmt(100.0 * level.soc_pulses),
        fmt(1000.0 * level.R0_ohm),
        fmt(1000.0 * level.R1_ohm),
        fmt(level.tau1_s),
        fmt(capacitance(level.tau1_s, level.R1_ohm)),
        fmt(level.rmse_fast_mV),
        fmt_int(level.n_pulses_used),
    ]


def slow_branch_row(level):
    """Table row of the slow branch for one fit_levels.csv row: R2, tau2 and C2 = tau2 / R2 at the SoC where the move ended."""
    return [
        fmt_int(level.level),
        fmt(100.0 * level.soc_rest),
        fmt(1000.0 * level.R2_ohm),
        fmt(level.tau2_s),
        fmt(capacitance(level.tau2_s, level.R2_ohm)),
        fmt(level.rmse_slow_mV),
    ]


def level_fit_lines(levels_df, temps):
    """Return the lines of the section on the HPPC level fits: per temperature a fast and a slow branch table.

    Levels are listed in level order. Columns of levels_df that are not used, such as the convergence flags, are ignored.
    """
    lines = [
        "## HPPC level fits",
        "",
        "Per level, R0, R1 and tau1 come from the four discharge pulses and their 40 s rests, and are tabulated "
        "at the SoC of the level's pulses. R2 and tau2 come from the 1 h rest after the move at that level, "
        "and are tabulated at the SoC where the move ended (docs/decisions.md 1.12). "
        "`pulses used` is the number of discharge pulses left in the fast fit.",
    ]
    fast_header = ["level", "SoC (%)", "R0 (mOhm)", "R1 (mOhm)", "tau1 (s)", "C1 (F)", "RMSE (mV)", "pulses used"]
    slow_header = ["level", "SoC (%)", "R2 (mOhm)", "tau2 (s)", "C2 (F)", "RMSE (mV)"]
    for temp in temps:
        levels = list(levels_df[levels_df["T_degC"] == temp].sort_values("level").itertuples())
        lines += ["", f"### {temp:g} degC", "", "Fast branch (RC 1):", ""]
        lines += md_table(fast_header, [fast_branch_row(level) for level in levels])
        lines += ["", "Slow branch (RC 2):", ""]
        lines += md_table(slow_header, [slow_branch_row(level) for level in levels])
    return lines


def params_md_text(params, levels_df, correction_df):
    """Return the text of results/params.md.

    params         the Params read from results/params.csv
    levels_df      results/fit_levels.csv as a DataFrame (one row per HPPC level)
    correction_df  results/ocv_correction.csv as a DataFrame (one row per HPPC rest point)
    """
    lines = [
        "# Model parameters",
        "",
        "Written by `python/export_params.py` from `results/params.csv` (the tables on the 101-point SoC grid, "
        "which the C file is generated from) and `results/fit_levels.csv` (the HPPC level fits before "
        "resampling). Do not edit by hand.",
        "",
        "Units: SoC in %, R in mOhm, tau in s, C = tau / R in F, RMSE in mV. "
        "`n/a` is a missing value: a failed fit, or R2 and tau2 of the last level, which has no 1 h rest.",
    ]
    for section in (ocv_lines(params), ocv_correction_lines(correction_df), level_fit_lines(levels_df, params.t_grid)):
        lines += ["", *section]
    return "\n".join(lines) + "\n"


# --- driver --------------------------------------------------------------------------------------


def export_params(
    params_csv=PARAMS_CSV,
    levels_csv=LEVELS_CSV,
    correction_csv=OCV_CORRECTION_CSV,
    md_path=PARAMS_MD,
    c_path=C_SOURCE,
    h_path=C_HEADER,
):
    """Read params.csv, fit_levels.csv and ocv_correction.csv and write params.md, the C source and the C header."""
    params = Params.from_csv(params_csv)
    write_c_files(params, c_path, h_path)
    write_text(md_path, params_md_text(params, pd.read_csv(levels_csv), pd.read_csv(correction_csv)))


def main():
    export_params()
    print("wrote " + ", ".join(str(path.relative_to(REPO_DIR)) for path in (PARAMS_MD, C_SOURCE, C_HEADER)))


if __name__ == "__main__":
    main()
