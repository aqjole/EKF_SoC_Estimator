"""Export the model tables: results/params.md and the generated C source and header.

Single source of truth (the spec, S1): results/params.csv holds the axes and the seven tables
(OCV, dOCV/dSoC, R0, R1, tau1, R2, tau2) on the 101-point SoC grid, results/fit_levels.csv holds
the HPPC level fits they were resampled from, and results/ocv_correction.csv holds the correction of the
OCV at each HPPC rest point. All three are written by python/fit_all.py. This script turns them into

  results/params.md       tables for the reader: the fit at each HPPC level, C = tau / R,
                          the fit RMSE, the OCV valid SoC range, the OCV fallback flag and the
                          OCV correction at the rest points
  c/include/ekf_params.h  extern declarations of the nine arrays and the two size defines
  c/src/ekf_params.c      the arrays as const float, one row per temperature

so Python and C look up the same numbers. Nothing is typed by hand and the output is deterministic:
running it twice on the same input gives byte-identical files.

Run from the repo root:  .venv/bin/python python/export_params.py
(fit_all.py calls export_params() after it has written the three CSV files.)
"""

from pathlib import Path

import numpy as np
import pandas as pd

from ekfsoc.constants import REPO_DIR, SOC_GRID, T_GRID_DEGC
from ekfsoc.model import Params


PARAMS_CSV = REPO_DIR / "results" / "params.csv"
LEVELS_CSV = REPO_DIR / "results" / "fit_levels.csv"
OCV_CORRECTION_CSV = REPO_DIR / "results" / "ocv_correction.csv"
PARAMS_MD = REPO_DIR / "results" / "params.md"
C_SOURCE = REPO_DIR / "c" / "src" / "ekf_params.c"
C_HEADER = REPO_DIR / "c" / "include" / "ekf_params.h"

# Significant digits of a float literal in the generated C file.
C_DIGITS = 7

# Literals per line in the generated C file.
C_VALUES_PER_LINE = 8

GENERATED_NOTE = "generated by python/export_params.py from results/params.csv, do not edit"

# The seven tables as C arrays: (attribute of Params, C name, what the table holds).
C_TABLES = (
    ("ocv", "ekf_ocv_v", "OCV in V"),
    ("docv", "ekf_docv_v_per_soc", "dOCV/dSoC in V per unit SoC"),
    ("r0", "ekf_r0_ohm", "R0 in Ohm"),
    ("r1", "ekf_r1_ohm", "R1 in Ohm"),
    ("tau1", "ekf_tau1_s", "tau1 in s"),
    ("r2", "ekf_r2_ohm", "R2 in Ohm"),
    ("tau2", "ekf_tau2_s", "tau2 in s"),
)


# --- C files -------------------------------------------------------------------------------------


def c_float(value):
    """Return `value` as a C99 float literal with 7 significant digits and an f suffix, e.g. 0.07f, 40.0f, 1e-05f.

    The f suffix makes the literal a float, not a double, which the build needs under
    -Wdouble-promotion. '%.7g' prints a whole number without a point ('40'), and '40f' is not a
    valid literal, so '.0' is added when the text has neither a point nor an exponent.
    A value that is not finite has no literal, so it raises ValueError.
    """
    if not np.isfinite(value):
        raise ValueError(f"cannot write {value} as a C float literal")
    text = f"%.{C_DIGITS}g" % value
    if "." not in text and "e" not in text:
        text += ".0"
    return text + "f"


def c_values_lines(values, indent):
    """Return the literals of one 1-D array as indented lines of C_VALUES_PER_LINE values, ending in commas."""
    lines = []
    for start in range(0, len(values), C_VALUES_PER_LINE):
        chunk = values[start : start + C_VALUES_PER_LINE]
        lines.append(indent + ", ".join(c_float(value) for value in chunk) + ",")
    return lines


def header_text(params):
    """Return the text of c/include/ekf_params.h: the size defines and extern declarations of nine arrays."""
    n_t = len(params.t_grid)
    n_soc = len(params.soc_grid)
    lines = [
        f"/* {GENERATED_NOTE}",
        " *",
        " * The model tables of docs/model.md on the two axes of C15. Table row j is the temperature",
        " * ekf_t_grid_degc[j] (descending, 40 down to -20 degC) and column m is the SoC ekf_soc_grid[m]",
        " * (ascending, 0 to 1). Read a table with the bilinear, clamped lookup of Eq. 4.",
        " */",
        "#ifndef EKF_PARAMS_H",
        "#define EKF_PARAMS_H",
        "",
        f"#define EKF_N_T {n_t}",
        f"#define EKF_N_SOC {n_soc}",
        "",
        "extern const float ekf_t_grid_degc[EKF_N_T];  /* temperature axis in degC */",
        "extern const float ekf_soc_grid[EKF_N_SOC];  /* SoC axis as a fraction */",
    ]
    for _, c_name, meaning in C_TABLES:
        lines.append(f"extern const float {c_name}[EKF_N_T][EKF_N_SOC];  /* {meaning} */")
    lines.append("")
    lines.append("#endif /* EKF_PARAMS_H */")
    return "\n".join(lines) + "\n"


def source_text(params):
    """Return the text of c/src/ekf_params.c: the two axes and the seven tables as const float arrays."""
    lines = [
        f"/* {GENERATED_NOTE} */",
        "",
        '#include "ekf_params.h"',
        "",
        "/* temperature axis in degC, one table row each */",
        "const float ekf_t_grid_degc[EKF_N_T] = {",
    ]
    lines += c_values_lines(params.t_grid, "    ")
    lines += ["};", "", "/* SoC axis as a fraction, one table column each */", "const float ekf_soc_grid[EKF_N_SOC] = {"]
    lines += c_values_lines(params.soc_grid, "    ")
    lines.append("};")

    for attribute, c_name, meaning in C_TABLES:
        table = getattr(params, attribute)
        lines += ["", f"/* {meaning} */", f"const float {c_name}[EKF_N_T][EKF_N_SOC] = {{"]
        for j in range(len(params.t_grid)):
            lines.append(f"    {{ /* T = {params.t_grid[j]:g} degC */")
            lines += c_values_lines(table[j], "        ")
            lines.append("    },")
        lines.append("};")
    return "\n".join(lines) + "\n"


def write_c_files(params, c_path, h_path):
    """Write the C source and header for `params`. The folders are created when missing."""
    if not np.allclose(params.t_grid, T_GRID_DEGC) or not np.allclose(params.soc_grid, SOC_GRID, rtol=0.0, atol=1e-6):
        raise ValueError("params axes are not the project grids (T_GRID_DEGC, SOC_GRID)")
    for path, text in ((Path(c_path), source_text(params)), (Path(h_path), header_text(params))):
        path.parent.mkdir(parents=True, exist_ok=True)
        # newline="\n" so the bytes are the same on every platform.
        with open(path, "w", newline="\n") as handle:
            handle.write(text)


# --- results/params.md ---------------------------------------------------------------------------


def fmt(value, digits=4):
    """Return `value` with `digits` significant digits and no exponent, or 'n/a' for a missing value.

    A failed fit has no value (an empty cell in fit_levels.csv, NaN once read), and so has the
    R2 and tau2 of the last HPPC level, which has no 1 h rest.
    """
    if value is None or not np.isfinite(value):
        return "n/a"
    return np.format_float_positional(float(value), precision=digits, unique=False, fractional=False, trim="-")


def fmt_int(value):
    """Return a count as text, or 'n/a' when it is missing."""
    if value is None or not np.isfinite(value):
        return "n/a"
    return str(int(value))


def capacitance(tau, resistance):
    """Return C = tau / R in F, or NaN when R is missing or not above zero.

    The RC branch has C = tau / R. A failed fit leaves R missing (NaN), and a fit that ends at a zero
    resistance has no finite C; neither may stop the export, and both print as 'n/a'.
    """
    if not resistance > 0.0:
        return float("nan")
    return tau / resistance


def md_table(header, rows):
    """Return a markdown table: `header` is a list of column titles and `rows` a list of lists of text."""
    lines = ["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(row) + " |")
    return lines


def ocv_valid_first_index(ocv_row):
    """Return the index of the first grid SoC where the OCV is measured, or None if the whole row is flat.

    Below the lowest SoC the C/20 discharge reached, the OCV table holds one value
    (docs/decisions.md 1.1), so the row starts with a run of equal values. The first grid SoC where
    the OCV changes from the node before it is the first one inside the measured range.
    A row that does not start with such a run (the 25 degC discharge reaches SoC 0) is valid from index 0.
    """
    n = len(ocv_row)
    last_equal = 0
    while last_equal + 1 < n and ocv_row[last_equal + 1] == ocv_row[last_equal]:
        last_equal += 1
    if last_equal == 0:
        return 0
    if last_equal + 1 < n:
        return last_equal + 1
    return None


def ocv_correction_lines(correction_df):
    """Return the lines of the section on the OCV correction: the rule, then one table row per rest point."""
    rows = [
        [f"{row.T_degC:g}", fmt(100.0 * row.soc), fmt(row.v_rest_V, 5), fmt(row.v_c20_V, 5), fmt(row.delta_mV)]
        for row in correction_df.itertuples()
    ]
    lines = [
        "",
        "## OCV correction from the HPPC rest voltages",
        "",
        "At each rest point (the last row of every 1 h rest after a move, and the last row before the first "
        "discharge pulse of level 1) delta = V rest - V C/20 at the same SoC, and a PCHIP through the deltas, "
        "held flat beyond the first and last point, is added to the C/20 curve (docs/decisions.md 1.1).",
        "",
    ]
    return lines + md_table(["T (degC)", "SoC (%)", "V rest (V)", "V C/20 (V)", "delta (mV)"], rows)


def params_md_text(params_df, levels_df, correction_df):
    """Return the text of results/params.md.

    params_df      results/params.csv as a DataFrame (606 rows, one per temperature and grid SoC)
    levels_df      results/fit_levels.csv as a DataFrame (one row per HPPC level; columns that are not
                   listed below, such as convergence flags, are ignored)
    correction_df  results/ocv_correction.csv as a DataFrame (one row per HPPC rest point)

    Contents: the OCV valid SoC range per temperature and the OCV fallback flag (from params_df),
    the OCV correction at the rest points (from correction_df),
    then per temperature two tables of the HPPC level fits: the fast branch (R0, R1, tau1,
    C1 = tau1 / R1 at the SoC of the level's pulses, with the RMSE and the number of pulses used)
    and the slow branch (R2, tau2, C2 = tau2 / R2 at the SoC where the move ended, with the RMSE).
    """
    temps = list(params_df["T_degC"].drop_duplicates())

    # Fallback: the spec copies the 25 degC OCV row to every temperature when a cold curve is not
    # monotone, so all rows are then equal.
    ocv_rows = [params_df.loc[params_df["T_degC"] == temp, "ocv_V"].to_numpy() for temp in temps]
    fallback_used = all(np.array_equal(ocv_rows[0], row) for row in ocv_rows)

    lines = [
        "# Model parameters",
        "",
        "Written by `python/export_params.py` from `results/params.csv` (the tables on the 101-point SoC grid, "
        "which the C file is generated from) and `results/fit_levels.csv` (the HPPC level fits before "
        "resampling). Do not edit by hand.",
        "",
        "Units: SoC in %, R in mOhm, tau in s, C = tau / R in F, RMSE in mV. "
        "`n/a` is a missing value: a failed fit, or R2 and tau2 of the last level, which has no 1 h rest.",
        "",
        "## OCV",
        "",
        "OCV comes from the C/20 discharge half, corrected onto the HPPC rest voltages (docs/decisions.md 1.1). "
        "Below the lowest SoC a discharge reached, the table holds its last value, so the OCV is measured from "
        "the first grid SoC where it changes from the node before it (from 0 when nothing is held).",
        "",
        f"OCV fallback (the 25 degC curve used at every temperature): {'yes' if fallback_used else 'no'}.",
        "",
    ]
    ocv_header = ["T (degC)", "OCV valid from SoC (%)", "grid points held below"]
    ocv_table_rows = []
    for temp, ocv_row in zip(temps, ocv_rows):
        soc_row = params_df.loc[params_df["T_degC"] == temp, "soc"].to_numpy()
        first = ocv_valid_first_index(ocv_row)
        if first is None:
            ocv_table_rows.append([f"{temp:g}", "n/a", str(len(ocv_row))])
        else:
            ocv_table_rows.append([f"{temp:g}", f"{100.0 * soc_row[first]:.1f}", str(first)])
    lines += md_table(ocv_header, ocv_table_rows)
    lines += ocv_correction_lines(correction_df)

    lines += [
        "",
        "## HPPC level fits",
        "",
        "Per level, R0, R1 and tau1 come from the four discharge pulses and their 40 s rests, and are tabulated "
        "at the SoC of the level's pulses. R2 and tau2 come from the 1 h rest after the move at that level, "
        "and are tabulated at the SoC where the move ended (docs/decisions.md 1.12). "
        "`pulses used` is the number of discharge pulses left in the fast fit.",
    ]

    fast_header = ["level", "SoC (%)", "R0 (mOhm)", "R1 (mOhm)", "tau1 (s)", "C1 (F)", "RMSE (mV)", "pulses used"]
    slow_header = ["level", "SoC (%)", "R2 (mOhm)", "tau2 (s)", "C2 (F)", "RMSE (mV)"]
    for temp in temps:
        levels = levels_df.loc[levels_df["T_degC"] == temp].sort_values("level")
        lines += ["", f"### {temp:g} degC", ""]
        if len(levels) == 0:
            lines.append("No level fits for this temperature.")
            continue

        fast_rows = []
        slow_rows = []
        for _, level in levels.iterrows():
            r1 = level["R1_ohm"]
            tau1 = level["tau1_s"]
            r2 = level["R2_ohm"]
            tau2 = level["tau2_s"]
            c1 = capacitance(tau1, r1)  # C1 = tau1 / R1, in F
            c2 = capacitance(tau2, r2)  # C2 = tau2 / R2, in F
            fast_rows.append(
                [
                    fmt_int(level["level"]),
                    fmt(100.0 * level["soc_pulses"]),
                    fmt(1000.0 * level["R0_ohm"]),
                    fmt(1000.0 * r1),
                    fmt(tau1),
                    fmt(c1),
                    fmt(level["rmse_fast_mV"]),
                    fmt_int(level["n_pulses_used"]),
                ]
            )
            slow_rows.append(
                [
                    fmt_int(level["level"]),
                    fmt(100.0 * level["soc_rest"]),
                    fmt(1000.0 * r2),
                    fmt(tau2),
                    fmt(c2),
                    fmt(level["rmse_slow_mV"]),
                ]
            )
        lines.append("Fast branch (RC 1):")
        lines.append("")
        lines += md_table(fast_header, fast_rows)
        lines += ["", "Slow branch (RC 2):", ""]
        lines += md_table(slow_header, slow_rows)

    return "\n".join(lines) + "\n"


# --- driver --------------------------------------------------------------------------------------


def export_params(
    params_csv=PARAMS_CSV,
    levels_csv=LEVELS_CSV,
    correction_csv=OCV_CORRECTION_CSV,
    md_path=PARAMS_MD,
    c_path=C_SOURCE,
    h_path=C_HEADER,
):
    """Read params.csv, fit_levels.csv and ocv_correction.csv and write params.md, the C source and the C header."""
    params = Params.from_csv(params_csv)
    params_df = pd.read_csv(params_csv)
    levels_df = pd.read_csv(levels_csv)
    correction_df = pd.read_csv(correction_csv)

    write_c_files(params, c_path, h_path)

    md_path = Path(md_path)
    md_path.parent.mkdir(parents=True, exist_ok=True)
    with open(md_path, "w", newline="\n") as handle:
        handle.write(params_md_text(params_df, levels_df, correction_df))


def main():
    export_params()
    written = [path.relative_to(REPO_DIR) for path in (PARAMS_MD, C_SOURCE, C_HEADER)]
    print("wrote " + ", ".join(str(path) for path in written))


if __name__ == "__main__":
    main()
