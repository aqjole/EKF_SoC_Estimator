"""Refit the S9 slow branches with v1.0 R1 under decision 1.44."""

from functools import partial
from multiprocessing import Pool

import numpy as np

from compare_r1i import load_params_ri
from ekfsoc.constants import T_GRID_DEGC
from ekfsoc.model import Params
from export_params import PARAMS_CSV, md_table, write_text
from fit_3rcd import (PARAMS_3RCD_CSV, calibrate_mix, fit_checks, load_params_3rcd, plot_nodes, score_open_loop,
                     write_nodes)
from fit_all import GATE_RMSE_MV, GATE_TEMP_DEGC
from s10_protocol import DISCLOSURE, PLOTS, RESULTS, splits, verify_baseline


PARAMS_CSV_D0 = RESULTS / "s10" / "params_3rcd0.csv"
NODES_CSV = RESULTS / "s10" / "fit_nodes_3rcd0.csv"
FIT_MD = RESULTS / "s10" / "model_fit_3rcd0.md"
MODELS = ("2RC", "2RC-I", "3RC-D", "3RC-D0", "S9 R1 substitution")
INCUMBENT, CANDIDATE, SUBSTITUTION = MODELS[1], MODELS[3], MODELS[4]


def load_candidate():
    return Params.from_csv(PARAMS_CSV_D0)


def load_substitution():
    """Use the original S9 slow-branch coefficients with v1.0 R1, without refitting."""
    return Params.from_csv(PARAMS_3RCD_CSV)


def score_split(specs, params):
    return score_open_loop((params,), specs)


def voltage_scores(base, candidate, mix, standard):
    models = (base, load_params_ri(), load_params_3rcd(), candidate, load_substitution())
    with Pool(processes=len(models)) as pool:
        in_sample = pool.map(partial(score_split, mix), models)
        regression = pool.map(partial(score_split, standard), models)
    return in_sample, regression


def voltage_lines(in_sample, regression):
    lines = []
    for label, scores in (("Mix calibration runs (in-sample)", in_sample), ("Standard regression runs", regression)):
        lines += [f"### {label}", "",
                  *md_table(["T (degC)", *MODELS],
                            [[str(t), *[f"{pooled[t][0]:.2f}" for pooled, _ in scores]] for t in T_GRID_DEGC]), ""]
    return lines


def fit_report(headers, nodes, fit, largest, folds, in_sample, regression):
    gate = regression[MODELS.index(CANDIDATE)][1][GATE_TEMP_DEGC][0][0]
    us06 = [us06 for _, us06 in regression]
    us06_rows = []
    for temp in T_GRID_DEGC:
        for part, name in enumerate(("Full", "Window", "Tail")):
            values = [scores[temp][part][0] for scores in us06]
            us06_rows.append([str(temp), name, *[f"{v:.4f}" if np.isfinite(v) else "n/a" for v in values]])
    return "\n".join([
        "# 3RC-D0 fit on the Mix runs (S10)", "", "Generated by `make fit-3rcd0` under decision 1.44.", "",
        DISCLOSURE, "",
        "3RC-D0 uses v1.0 R1 for both current signs. It refits R3 and the R2 scale using the S9 protocol. "
        "The S9 R1 substitution uses the original S9 R2/R3 tables with v1.0 R1 and has no refit.", "",
        "## Fit and checks", "", *fit_checks(fit, largest), "",
        "Bound flags are -1 for lower, +1 for upper and 0 for no active solver bound.", "",
        *md_table(headers, nodes), "",
        "## US06 voltage gate", "",
        f"**{'PASS' if gate <= GATE_RMSE_MV else 'FAIL'}.** "
        f"3RC-D0 full-run RMSE at {GATE_TEMP_DEGC} degC is {gate:.12g} mV (limit {GATE_RMSE_MV:g} mV).", "",
        "US06 voltage RMSE in mV. Scores use the reloaded tables.", "",
        *md_table(["T (degC)", "Scope", *MODELS], us06_rows), "",
        "## Open-loop voltage", "",
        "RMSE in mV pooled over evaluation-window rows using the reloaded tables.", "",
        *voltage_lines(in_sample, regression),
        "## Leave-one-Mix-run-out voltage", "",
        "Mean of per-run window RMSE in mV. Each fold fits the other 39 Mix runs and recomputes node support.", "",
        *md_table(["T (degC)", "2RC", "3RC-D0"],
                  [[str(t), *[f"{v:.2f}" for v in np.mean(folds[t], axis=0)]] for t in T_GRID_DEGC]), "",
        "The [diagnostic report](accuracy_diagnostics.md) records the frozen input hashes and run membership.", "",
    ])


def main():
    verify_baseline()
    mix, standard = splits()
    base = Params.from_csv(PARAMS_CSV)
    params, values, bound, fit, support, largest, folds = calibrate_mix(base, mix)
    headers, rows = write_nodes(NODES_CSV, base, values, bound, support)
    params.to_csv(PARAMS_CSV_D0)
    print("Scoring the exported tables on both splits", flush=True)
    in_sample, regression = voltage_scores(base, load_candidate(), mix, standard)
    write_text(FIT_MD, fit_report(headers, rows, fit, largest, folds, in_sample, regression))
    plot_nodes(base, values, PLOTS / "params_3rcd0.png")
    print("3RC-D0 fit report written", flush=True)


if __name__ == "__main__":
    main()
