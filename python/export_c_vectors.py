"""Export test vectors for the C unit tests: c/tests/vectors/vectors.h, computed by the Python filter.

The C port (c/src/ekf.c) mirrors ekf.py function for function, so each function gets one case with the
values Python computes, read from results/params.csv and the frozen noise settings of
results/ekf_config.json:

  interp2    four lookups (Eq. 4): on a node, between nodes on both axes, clamped beyond both axes at
             the top and at the bottom
  predict    one step of Eq. 6 and 7 at 25 degC from a state with a correlated P
  update     one update of Eq. 8 to 11 at 25 degC from the state the predict case ends in
  limit_soc  the projection of Eq. 10 from a SoC above 1, with the P the update case ends in

Every value is printed with 17 significant digits as an EKF_R(...) literal, so the double build reads
the very doubles Python used. The output is deterministic.

Run from the repo root:  .venv/bin/python python/export_c_vectors.py
"""

import copy

import numpy as np

from ekfsoc.constants import REPO_DIR
from ekfsoc.ekf import Ekf, EkfConfig
from ekfsoc.model import Params
import export_params
from export_params import C_TABLES, PARAMS_CSV, write_text
from tune import CONFIG_JSON


VECTORS_H = REPO_DIR / "c" / "tests" / "vectors" / "vectors.h"

GENERATED_NOTE = (
    "generated by python/export_c_vectors.py from results/params.csv and results/ekf_config.json, do not edit"
)

# The C array of each table, by its Params attribute.
C_TABLE_NAMES = {attribute: c_name for attribute, c_name, _ in C_TABLES}

# interp2 cases: (table, temperature in degC, SoC). 25 degC and SoC 0.5 are grid nodes; 17.3 degC lies
# between 25 and 10 and SoC 0.537 between 0.53 and 0.54; the last two lie beyond both axis ends.
INTERP2_CASES = (
    ("ocv", 25.0, 0.5),
    ("r0", 17.3, 0.537),
    ("r1", 55.0, 1.2),
    ("tau2", -30.0, -0.1),
)

# The state the predict case starts from: mid-range SoC, V1 and V2 of a few mV, and a P whose
# off-diagonal terms are not small, so every product of Eq. 7 and 11 matters.
TEMP_DEGC = 25.0
X_START = (0.62, 0.012, 0.025)
P_START = (
    (4e-3, 2e-4, 6e-4),
    (2e-4, 1e-4, 5e-5),
    (6e-4, 5e-5, 4e-4),
)
I_A = 2.5  # discharge current, held over the predict step and measured at the update
DT_S = 1.0  # a 1 s step, so that Q and the RC decay change P by more than the float tolerance

# The update case measures the voltage it predicts plus this innovation, rounded to 0.1 mV like a logged value.
INNOVATION_V = 0.008

# The limit_soc case: a posterior SoC above 1, with V1 and V2 of a few mV.
X_ABOVE_ONE = (1.004, 0.003, 0.009)


def c_literal(value):
    """Return `value` as EKF_R(...) with 17 significant digits, enough to give back the same double."""
    return export_params.c_literal(value, digits=17)


def c_vector(values):
    """Return a 1-D sequence as a C initializer, e.g. { EKF_R(...), EKF_R(...) }."""
    return "{ " + ", ".join(c_literal(value) for value in values) + " }"


def c_state(x, P, indent):
    """Return the lines of a vec_state_t initializer for state x and covariance P."""
    rows = [f"{indent}        {c_vector(row)}," for row in P]
    return [f"{indent}{{", f"{indent}    {c_vector(x)},", f"{indent}    {{", *rows, f"{indent}    }},", f"{indent}}},"]


def interp2_lines(params, cfg):
    """Return the vec_interp2 array: one row per INTERP2_CASES entry with the value Python looks up."""
    ekf = Ekf(params, cfg, 0.0)
    lines = ["static const vec_interp2_t vec_interp2[VEC_N_INTERP2] = {"]
    for name, temp, soc in INTERP2_CASES:
        expected = ekf.lookup(name, temp, soc)
        lines.append(f"    {{ &{C_TABLE_NAMES[name]}[0][0], {c_literal(temp)}, {c_literal(soc)}, {c_literal(expected)} }},")
    return lines + ["};"]


def step_cases(params, cfg):
    """Run the predict, update and limit_soc cases in Python and return their C initializers.

    The update starts from the state the predict ends in, and limit_soc uses the P the update ends in,
    so the three cases follow one step of the filter.
    """
    ekf = Ekf(params, cfg, 0.0)
    x_start = np.array(X_START)
    p_start = np.array(P_START)
    x_above_one = np.array(X_ABOVE_ONE)
    if params.r3 is not None:
        x_start = np.r_[x_start, 0.008]
        x_above_one = np.r_[x_above_one, 0.005]
        p_start = np.pad(p_start, (0, 1))
        v3_covariance = [1.1e-4, 1e-5, 6e-5, 1.6e-4]
        p_start[-1, :] = p_start[:, -1] = v3_covariance
    ekf.x, ekf.P = x_start.copy(), p_start.copy()
    ekf.predict(I_A, TEMP_DEGC, DT_S)
    x_predicted, P_predicted = ekf.x.copy(), ekf.P.copy()

    # The measured voltage: what the filter predicts at the update (y_hat does not depend on the
    # measurement, so a copy updated with any voltage gives it), plus the innovation.
    probe = copy.deepcopy(ekf)
    probe.update(I_A, 0.0, TEMP_DEGC)
    v_v = round(probe.y_hat + INNOVATION_V, 4)
    ekf.update(I_A, v_v, TEMP_DEGC)
    x_updated, P_updated = ekf.x.copy(), ekf.P.copy()

    x_limited = ekf.limit_soc(x_above_one, P_updated)

    return [
        "static const vec_predict_t vec_predict = {",
        *c_state(x_start, p_start, "    "),
        f"    {c_literal(I_A)}, {c_literal(TEMP_DEGC)}, {c_literal(DT_S)},",
        *c_state(x_predicted, P_predicted, "    "),
        "};",
        "",
        "static const vec_update_t vec_update = {",
        *c_state(x_predicted, P_predicted, "    "),
        f"    {c_literal(I_A)}, {c_literal(v_v)}, {c_literal(TEMP_DEGC)},",
        *c_state(x_updated, P_updated, "    "),
        f"    {c_literal(ekf.y_hat)},",
        "};",
        "",
        "static const vec_limit_soc_t vec_limit_soc = {",
        *c_state(x_above_one, P_updated, "    "),
        f"    {c_vector(x_limited)},",
        "};",
    ]


def vectors_text(params, cfg, *, note=GENERATED_NOTE, header="ekf_params.h"):
    """Return the text of c/tests/vectors/vectors.h."""
    n_state = len(params.branches) + 1
    state_names = ", ".join(["SoC", *[f"V{k}" for k in range(1, n_state)]])
    lines = [
        f"/* {note}",
        " *",
        " * Inputs and the values the Python filter (python/ekfsoc/ekf.py) computes from them, for the C unit",
        f" * tests. Tables and grids are those of {header}; the noise settings are VEC_Q_SOC, VEC_Q_V, VEC_R.",
        " */",
        "#ifndef EKF_TEST_VECTORS_H",
        "#define EKF_TEST_VECTORS_H",
        "",
        f'#include "{header}"',
        '#include "ekf_types.h"',
        "",
        f"#define VEC_Q_SOC {c_literal(cfg.q_soc)}",
        f"#define VEC_Q_V {c_literal(cfg.q_v)}",
        f"#define VEC_R {c_literal(cfg.r)}",
        f"#define VEC_N_INTERP2 {len(INTERP2_CASES)}",
        "",
        "/* One lookup of Eq. 4: table (row-major [EKF_N_T][EKF_N_SOC]) read at (t_degc, soc). */",
        "typedef struct {",
        "    const ekf_real_t *table;",
        "    ekf_real_t t_degc;",
        "    ekf_real_t soc;",
        "    ekf_real_t expected;",
        "} vec_interp2_t;",
        "",
        f"/* A filter state x = [{state_names}] and its covariance P. */",
        "typedef struct {",
        f"    ekf_real_t x[{n_state}];",
        f"    ekf_real_t P[{n_state}][{n_state}];",
        "} vec_state_t;",
        "",
        "/* predict (Eq. 6, 7): before, then i_held over dt_s at t_degc, gives after. */",
        "typedef struct {",
        "    vec_state_t before;",
        "    ekf_real_t i_held, t_degc, dt_s;",
        "    vec_state_t after;",
        "} vec_predict_t;",
        "",
        "/* update (Eq. 8 to 11): before, then v_v measured at i_a and t_degc, gives after and y_hat. */",
        "typedef struct {",
        "    vec_state_t before;",
        "    ekf_real_t i_a, v_v, t_degc;",
        "    vec_state_t after;",
        "    ekf_real_t y_hat;",
        "} vec_update_t;",
        "",
        "/* limit_soc (Eq. 10): before.x with SoC above 1 and before.P give x; P is not changed. */",
        "typedef struct {",
        "    vec_state_t before;",
        f"    ekf_real_t x[{n_state}];",
        "} vec_limit_soc_t;",
        "",
        *interp2_lines(params, cfg),
        "",
        *step_cases(params, cfg),
        "",
        "#endif /* EKF_TEST_VECTORS_H */",
    ]
    return "\n".join(lines) + "\n"


def main():
    params = Params.from_csv(PARAMS_CSV)
    cfg = EkfConfig.from_json(CONFIG_JSON)
    write_text(VECTORS_H, vectors_text(params, cfg))
    print(f"wrote {VECTORS_H.relative_to(REPO_DIR)}")


if __name__ == "__main__":
    main()
