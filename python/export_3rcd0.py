"""Generate the adopted model's C tables and four-state Python test vectors."""

import numpy as np

from ekfsoc.constants import REPO_DIR
from ekfsoc.ekf import EkfConfig
from ekfsoc.model import Params
from export_c_vectors import vectors_text
from export_params import C_TABLES, write_c_files, write_text
from fit_3rcd import TAU3


PARAMS_CSV = REPO_DIR / "results" / "params_3rcd0.csv"
CONFIG_JSON = REPO_DIR / "results" / "ekf_config.json"
SOURCE = REPO_DIR / "c" / "src" / "ekf_params_3rcd0.c"
HEADER = REPO_DIR / "c" / "include" / "ekf_params_3rcd0.h"
VECTORS = REPO_DIR / "c" / "tests" / "vectors" / "vectors_3rcd0.h"
TABLES = C_TABLES + (("r3", "ekf_r3_ohm", "R3 in Ohm"),)
NOTE = "generated by python/export_3rcd0.py from results/params_3rcd0.csv, do not edit"


def main():
    params = Params.from_csv(PARAMS_CSV)
    if params.tau3 is None or not np.all(params.tau3 == TAU3):
        raise ValueError(f"3RC-D0 requires a third branch with tau3 fixed at {TAU3:g} s")
    write_c_files(params, SOURCE, HEADER, tables=TABLES, note=NOTE, tau3_s=TAU3)
    cfg = EkfConfig.from_json(CONFIG_JSON)
    write_text(VECTORS, vectors_text(params, cfg, note=NOTE, header=HEADER.name))


if __name__ == "__main__":
    main()
