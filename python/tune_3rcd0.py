"""The fixed 864 + 81 point S11 search; never changes the incumbent config."""

import argparse
import itertools
import json
import time
from hashlib import sha256
from multiprocessing import Pool

import matplotlib.pyplot as plt
import numpy as np

from ekfsoc.constants import REPO_DIR
from ekfsoc.plots import save
from export_params import md_table, write_text
from s10_protocol import DISCLOSURE, RESULTS, splits, verify_baseline
from s11_native import build
from s11_search import config, objective, reference_objective, score_point, validate_native
from tune import GRIDS, refine_points


AXES = GRIDS | {"p0_v_std": (.015, .05, .15)}
CONFIG = RESULTS / "s11" / "ekf_config_3rcd0.json"
REPORT = RESULTS / "s11" / "tuning_3rcd0.md"
CHECKPOINT = RESULTS / "runs" / "s11_tuning" / "search.json"
PLOT = RESULTS / "plots" / "s11" / "tuning_3rcd0.png"


def fingerprint():
    """Content, not HEAD or mtime; includes raw inputs and all Python implementation."""
    paths = [s.path for s in splits()[0]]
    paths += [REPO_DIR / "python" / name for name in
              ("tune_3rcd0.py", "s11_search.py", "s11_native.py", "tune.py", "s10_protocol.py",
               "fit_3rcd0.py", "fit_3rcd.py")]
    paths += list((REPO_DIR / "python" / "ekfsoc").glob("*.py"))
    paths += [REPO_DIR / "c/tools/ekf_tuning.c", RESULTS / "s10" / "params_3rcd0.csv",
              RESULTS / "s2" / "ekf_config.json"]
    return {str(p.relative_to(REPO_DIR)): sha256(p.read_bytes()).hexdigest() for p in sorted(set(paths))}


def checkpoint(state):
    CHECKPOINT.parent.mkdir(parents=True, exist_ok=True)
    temporary = CHECKPOINT.with_suffix(".tmp")
    temporary.write_text(json.dumps(state, indent=2, allow_nan=False) + "\n")
    temporary.replace(CHECKPOINT)


def search(pool, state, label, points):
    records = state.setdefault(label, {})
    pending = [(i, p) for i, p in enumerate(points) if str(i) not in records]
    started, elapsed = time.monotonic(), state.get("wall_s", 0.)
    for index, score in pool.imap_unordered(score_point, pending, chunksize=1):
        records[str(index)] = score
        state["wall_s"] = elapsed + time.monotonic() - started
        checkpoint(state)
        if len(records) % 24 == 0 or len(records) == len(points):
            print(f"{label}: {len(records)}/{len(points)}, best {min(records.values()):.6f} pp", flush=True)
    return [(tuple(point), records[str(i)]) for i, point in enumerate(points)]


def best_reference(pool, scored):
    """Resolve potential numerical ties in Python, keeping original evaluation order."""
    lowest = min(score for _, score in scored)
    contenders = [(i, p, s) for i, (p, s) in enumerate(scored) if s <= lowest + 1e-6]
    checked = []
    for i, point, score in contenders:
        halves = reference_objective(pool, point)
        value = float(np.mean(halves))
        if abs(value - score) > 1e-6:
            raise ValueError("Native and Python objectives disagree")
        checked.append((value, i, point, halves))
    value, _, point, halves = min(checked, key=lambda row: (row[0], row[1]))
    return point, value, halves


def report(grid, refined, chosen, baseline, state):
    grid_best = state["grid_best"]
    point, value, halves = chosen
    edge = [name for name, x in zip(AXES, grid_best) if x in (AXES[name][0], AXES[name][-1])]
    ends = [name for name, x, old in zip(AXES, point, grid_best) if x != old]
    rows = [[label, *[f"{v:.8f}" for v in values], f"{np.mean(values):.8f}"]
            for label, values in (("Incumbent", baseline), ("Candidate", halves))]
    lines = ["# 3RC-D0 settings search (S11 A)", "", "Generated by `make tune-3rcd0`; decisions 1.49–1.50.", "",
             DISCLOSURE, "", "## Method", "",
             "40 Mix runs only; per-run mean of experiment-2 and experiment-4 RMSE, then mean within each "
             "temperature and equal mean across all six temperatures. p0_soc_std remains 0.2. "
             "The unchanged 3RC-D0 tables and legacy Jacobians are used throughout.", "",
             "864 grid points, then 81 points at factors 1/3, 1 and 3 around the grid winner, rounded to "
             "three significant digits. Evaluation order has q_soc slowest and p0_v_std fastest; ties retain "
             "that order. Near ties and the chosen objective are checked in Python. The offline C evaluator "
             "passes per-row absolute tolerance 1e-8 for SoC and voltage at incumbent and extreme settings "
             "on six temperatures before search, and on all 40 Mix runs at each checked winner.", "",
             f"Search wall time (completed grid/refinement work): {state['wall_s']:.1f} s. "
             "Reference checks are excluded. A resumed search sums active search time.", "",
             "## Selected candidate", "", f"Settings: `{dict(zip(AXES, point))}`.", "",
             "These settings are an experimental candidate; adoption is decided in "
             "[the comparison report](model_compare_3rcd0n.md). The S2 config is untouched.", "",
             f"Grid edge: {', '.join(edge) or 'none'}. Refinement range end: {', '.join(ends) or 'none'}. "
             "The search is not extended; the objective may fall beyond an edge.", "",
             *md_table(["Settings", "Exp2 (pp)", "Exp4 (pp)", "Objective (pp)"], rows), "",
             "## Grid winners by initial branch standard deviation", ""]
    winners = [min((row for row in grid if row[0][3] == p0), key=lambda row: row[1]) for p0 in AXES["p0_v_std"]]
    lines += md_table([*AXES, "Objective (pp)"], [[*[f"{x:.3g}" for x in p], f"{v:.8f}"] for p, v in winners])
    lines += ["", "Guard-7 counts for these three settings are reported with the comparison.", ""]
    for label, scored in (("Grid", grid), ("Refinement", refined)):
        lines += [f"## {label}: all {len(scored)} objectives in evaluation order", ""]
        lines += md_table(["Index", *AXES, "Objective (pp)"],
                          [[str(i), *[f"{x:.3g}" for x in p], f"{v:.8f}"] for i, (p, v) in enumerate(scored)]) + [""]
    lines += ["## Input and implementation hashes", ""]
    lines += md_table(["Path", "SHA-256"], list(state["inputs"].items())) + [""]
    write_text(REPORT, "\n".join(lines))
    fig, axes = plt.subplots(2, 2, figsize=(9, 6))
    for ax, k, name in zip(axes.flat, range(4), AXES):
        for label, scored, center in (("Grid", grid, grid_best), ("Refinement", refined, point)):
            curve = [(p[k], score) for p, score in scored if all(p[j] == center[j] for j in range(4) if j != k)]
            curve.sort()
            ax.semilogx([x for x, _ in curve], [y for _, y in curve], "o-", label=label)
        ax.set(xlabel=name, ylabel="Objective (pp)")
        ax.grid(alpha=.25)
    axes.flat[0].legend()
    save(fig, PLOT)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--workers", type=int, default=6)
    args = parser.parse_args()
    verify_baseline()
    build()
    inputs = fingerprint()
    state = json.loads(CHECKPOINT.read_text()) if CHECKPOINT.exists() else {"inputs": inputs}
    if state["inputs"] != inputs:
        raise ValueError(f"Stale checkpoint; archive {CHECKPOINT} before starting a new search")
    with Pool(args.workers) as pool:
        if not state.get("validated"):
            print("Validating native evaluator against Python at six temperatures", flush=True)
            validate_native(pool)
            state["validated"] = True
            checkpoint(state)
        grid = search(pool, state, "grid", list(itertools.product(*AXES.values())))
        print("Checking grid winner in Python", flush=True)
        grid_best = best_reference(pool, grid)
        state["grid_best"] = grid_best[0]
        refined = search(pool, state, "refined", refine_points(grid_best[0]))
        print("Checking refined winner and incumbent in Python", flush=True)
        chosen = best_reference(pool, refined)
        baseline = reference_objective(pool, (1e-7, 1e-6, .01, .05))
    config(chosen[0]).to_json(CONFIG)
    report(grid, refined, chosen, baseline, state)
    print(f"Candidate {chosen[0]}: {chosen[1]:.8f} pp; incumbent {np.mean(baseline):.8f} pp", flush=True)


if __name__ == "__main__":
    main()
