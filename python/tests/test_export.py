"""Tests for export_params: the generated C files and results/s1/params.md.

No raw data and no real fit is needed. Each test writes a small synthetic params.csv, fit_levels.csv and
ocv_correction.csv in tmp_path, runs the export on them and checks the output: the C source compiles
under strict flags in the float and the double build, the header has the size and Q_ref defines, the
nine declarations and the ekf_params_t struct, every literal goes through EKF_R, the values round-trip to
the CSV, and two runs give the same bytes.
"""

import math
import re
import shutil
import subprocess

import numpy as np
import pandas as pd
import pytest

import export_params
from ekfsoc.constants import Q_REF_AH, REPO_DIR, SOC_GRID, T_GRID_DEGC
from ekfsoc.model import Params


# Lowest SoC the C/20 discharge reaches at 40, 25, 10, 0, -10, -20 degC (results/s0/data_checks.md section 11).
SOC_MIN = [0.0327, 0.0, 0.0474, 0.0655, 0.0781, 0.1028]

# Levels of the six HPPC files (docs/decisions.md 1.2).
N_LEVELS = [11, 12, 11, 10, 10, 9]

C_ARRAY_NAMES = [
    "ekf_t_grid_degc",
    "ekf_soc_grid",
    "ekf_ocv_v",
    "ekf_docv_v_per_soc",
    "ekf_r0_ohm",
    "ekf_r1_ohm",
    "ekf_tau1_s",
    "ekf_r2_ohm",
    "ekf_tau2_s",
]

# Table arrays and the params.csv column each one holds.
C_NAME_TO_COLUMN = {
    "ekf_ocv_v": "ocv_V",
    "ekf_docv_v_per_soc": "docv_V_per_soc",
    "ekf_r0_ohm": "R0_ohm",
    "ekf_r1_ohm": "R1_ohm",
    "ekf_tau1_s": "tau1_s",
    "ekf_r2_ohm": "R2_ohm",
    "ekf_tau2_s": "tau2_s",
}

GENERATED_NOTE_START = "/* generated by python/export_params.py from results/s1/params.csv, do not edit"

# The hand-written header with ekf_real_t and EKF_R, which the generated files include.
TYPES_DIR = REPO_DIR / "c" / "include"

# EKF_R(...) around a literal, capturing the literal.
EKF_R_LITERAL = r"EKF_R\(([^)]*)\)"


# --- synthetic inputs ----------------------------------------------------------------------------


def synthetic_params(fallback=False):
    """Seven smooth tables on the project grids that differ in every row and column.

    The OCV rises with SoC and is held at its SoC_MIN value below SoC_MIN of each temperature (the same
    hold rule as build_ocv). `fallback=True` copies the 25 degC OCV row to every temperature.
    """
    soc = SOC_GRID[None, :]
    temp = np.array(T_GRID_DEGC, dtype=float)[:, None]
    cold = (25 - temp) / 45.0
    held = np.maximum(soc, np.array(SOC_MIN)[:, None])
    ocv = 3.0 + 0.9 * held + 0.35 * held**3 - 0.002 * (25 - temp) * (1.0 - held)
    if fallback:
        ocv = np.tile(ocv[1], (len(T_GRID_DEGC), 1))
    return Params(
        t_grid=T_GRID_DEGC,
        soc_grid=SOC_GRID,
        ocv=ocv,
        docv=np.gradient(ocv, SOC_GRID, axis=1),
        r0=0.02 * (1.0 + cold) * (1.0 + 0.5 * (1.0 - soc)),
        r1=0.01 * (1.0 + 1.5 * cold) * (1.0 + 0.3 * (1.0 - soc)),
        tau1=3.0 * (1.0 + cold) * (1.0 + 0.2 * soc),
        r2=0.015 * (1.0 + cold) * (1.0 + 0.1 * soc),
        tau2=300.0 * (1.0 + cold) * (1.0 + 0.5 * soc),
    )


def synthetic_levels():
    """HPPC level fits as fit_levels.csv has them.

    The last level of each temperature has no 1 h rest, so its slow-fit cells are empty. The first level at
    -20 degC is a failed fast fit, which is empty too.
    """
    rows = []
    for temp, n_levels in zip(T_GRID_DEGC, N_LEVELS):
        cold = (25 - temp) / 45.0
        for level in range(1, n_levels + 1):
            last = level == n_levels
            failed = temp == -20 and level == 1
            rows.append({
                "T_degC": temp,
                "level": level,
                "soc_pulses": 1.0 - 0.09 * (level - 1),
                "R0_ohm": np.nan if failed else 0.02 * (1.0 + cold),
                "R1_ohm": np.nan if failed else 0.01 * (1.0 + 1.5 * cold),
                "tau1_s": np.nan if failed else 3.0 * (1.0 + cold),
                "rmse_fast_mV": np.nan if failed else 1.2,
                "n_pulses_used": 0 if failed else 4,
                "soc_rest": np.nan if last else 1.0 - 0.09 * level,
                "R2_ohm": np.nan if last else 0.015 * (1.0 + cold),
                "tau2_s": np.nan if last else 300.0 * (1.0 + cold),
                "rmse_slow_mV": np.nan if last else 0.8,
                "fast_ok": not failed,
                "slow_ok": None if last else True,
            })
    return pd.DataFrame(rows)


def synthetic_correction():
    """Three rest points per temperature, SoC falling; the delta is 10 mV at 100 % and grows towards low SoC."""
    rows = []
    for temp in T_GRID_DEGC:
        for soc, delta_mv in ((1.0, 10.0), (0.5, 20.0), (0.1, 60.0)):
            v_c20 = 3.5 + 0.7 * soc
            rows.append({"T_degC": temp, "soc": soc, "v_rest_V": v_c20 + delta_mv / 1000.0, "v_c20_V": v_c20,
                         "delta_mV": delta_mv})
    return pd.DataFrame(rows)


def run_export(directory, fallback=False):
    """Write the synthetic inputs into `directory`, run export_params into its out/ folder and return the three output paths."""
    synthetic_params(fallback).to_csv(directory / "params.csv")
    synthetic_levels().to_csv(directory / "fit_levels.csv", index=False, float_format="%.6g")
    synthetic_correction().to_csv(directory / "ocv_correction.csv", index=False, float_format="%.6g")
    out = directory / "out"
    paths = (out / "params.md", out / "src" / "ekf_params.c", out / "include" / "ekf_params.h")
    export_params.export_params(
        directory / "params.csv", directory / "fit_levels.csv", directory / "ocv_correction.csv", *paths
    )
    return paths


# --- C files -------------------------------------------------------------------------------------


def strip_comments(text):
    """Remove /* ... */ comments from C text."""
    return re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)


def array_values(c_text, name):
    """Return the literals of the C array `name` as a flat float array (EKF_R removed, comments ignored)."""
    code = strip_comments(c_text)
    match = re.search(r"const ekf_real_t " + name + r"\[[^=]*=\s*\{(.*?)\n\};", code, flags=re.DOTALL)
    assert match, f"array {name} not found"
    return np.array([float(token) for token in re.findall(EKF_R_LITERAL, match.group(1))])


@pytest.mark.skipif(shutil.which("cc") is None, reason="no C compiler (cc) on this machine")
@pytest.mark.parametrize(("defines", "real_size"), [([], 4), (["-DEKF_USE_DOUBLE"], 8)], ids=["float", "double"])
def test_c_source_compiles_under_strict_flags_and_the_compiler_reads_the_csv_values(tmp_path, defines, real_size):
    # Build a tiny main against the generated files with the strict flags of the C library, run it and
    # check three table entries: the compiler's own reading of the literals, not only ours. The last one
    # is read through ekf_params_default, row-major, so the struct and its layout are checked too.
    _, c_path, h_path = run_export(tmp_path)
    main_path = tmp_path / "check_main.c"
    main_path.write_text(
        '#include <stdio.h>\n#include "ekf_params.h"\n'
        "int main(void) {\n"
        '    printf("%d %d %d\\n", EKF_N_T, EKF_N_SOC, (int)sizeof(ekf_real_t));\n'
        '    printf("%.7g %.7g %.7g\\n", (double)ekf_t_grid_degc[5], (double)ekf_ocv_v[0][0],\n'
        "           (double)ekf_params_default.tau2[5 * EKF_N_SOC + 100]);\n"
        "    return 0;\n}\n"
    )
    exe_path = tmp_path / "check_main"
    command = [
        "cc", "-std=c99", "-Wall", "-Wextra", "-Wpedantic", "-Werror", "-Wdouble-promotion", *defines,
        "-I", str(h_path.parent), "-I", str(TYPES_DIR), str(c_path), str(main_path), "-o", str(exe_path),
    ]  # fmt: skip
    build = subprocess.run(command, capture_output=True, text=True)
    assert build.returncode == 0, build.stderr
    output = subprocess.run([str(exe_path)], capture_output=True, text=True, check=True).stdout.split("\n")

    assert output[0] == f"6 101 {real_size}"
    t_last, ocv_first, tau2_last = (float(word) for word in output[1].split())
    params_df = pd.read_csv(tmp_path / "params.csv")
    assert t_last == -20.0
    assert ocv_first == pytest.approx(params_df["ocv_V"].iloc[0], rel=1e-6)
    assert tau2_last == pytest.approx(params_df["tau2_s"].iloc[-1], rel=1e-6)


def test_header_defines_sizes_and_declares_nine_arrays(tmp_path):
    _, _, h_path = run_export(tmp_path)
    text = h_path.read_text()

    assert '#include "ekf_types.h"' in text
    assert re.search(r"^#define EKF_N_T 6$", text, flags=re.MULTILINE)
    assert re.search(r"^#define EKF_N_SOC 101$", text, flags=re.MULTILINE)
    assert re.findall(r"^extern const ekf_real_t (\w+)\[", text, flags=re.MULTILINE) == C_ARRAY_NAMES
    assert "#ifndef EKF_PARAMS_H" in text and "#endif" in text


def test_header_defines_q_ref_from_the_python_constant(tmp_path):
    _, _, h_path = run_export(tmp_path)
    define = re.search(r"^#define EKF_Q_REF_AH " + EKF_R_LITERAL, h_path.read_text(), flags=re.MULTILINE)
    assert float(define.group(1)) == Q_REF_AH


def test_header_has_the_params_struct_with_one_pointer_per_array(tmp_path):
    _, _, h_path = run_export(tmp_path)
    struct = re.search(r"typedef struct \{(.*?)\} ekf_params_t;", h_path.read_text(), flags=re.DOTALL).group(1)
    fields = re.findall(r"const ekf_real_t \*(\w+);", struct)
    assert fields == ["t_grid", "soc_grid", "ocv", "docv", "r0", "r1", "tau1", "r2", "tau2"]


def test_default_params_point_at_the_arrays_in_order(tmp_path):
    _, c_path, h_path = run_export(tmp_path)
    assert "extern const ekf_params_t ekf_params_default;" in h_path.read_text()
    default = re.search(r"const ekf_params_t ekf_params_default = \{(.*?)\};", c_path.read_text(), flags=re.DOTALL)
    targets = re.findall(r"= &?(\w+)", default.group(1))
    assert targets == C_ARRAY_NAMES


def test_both_c_files_start_with_the_generated_note(tmp_path):
    _, c_path, h_path = run_export(tmp_path)
    assert c_path.read_text().startswith(GENERATED_NOTE_START)
    assert h_path.read_text().startswith(GENERATED_NOTE_START)


def test_every_literal_goes_through_ekf_r_in_scientific_notation(tmp_path):
    _, c_path, _ = run_export(tmp_path)
    literals = re.findall(EKF_R_LITERAL, strip_comments(c_path.read_text()))
    # 6 temperatures + 101 SoC nodes + 7 tables of 606 values.
    assert len(literals) == 6 + 101 + 7 * 606
    for literal in literals:
        assert re.fullmatch(r"-?\d\.\d{6}e[+-]\d{2}", literal), literal  # 7 significant digits, always a point


def test_c_values_round_trip_to_the_csv(tmp_path):
    _, c_path, _ = run_export(tmp_path)
    c_text = c_path.read_text()
    params_df = pd.read_csv(tmp_path / "params.csv")

    assert list(array_values(c_text, "ekf_t_grid_degc")) == T_GRID_DEGC
    assert array_values(c_text, "ekf_soc_grid") == pytest.approx(SOC_GRID, abs=1e-6)
    for c_name, column in C_NAME_TO_COLUMN.items():
        # Every entry in row order (T-major), so a swapped row or column would fail.
        assert array_values(c_text, c_name) == pytest.approx(params_df[column].to_numpy(), rel=1e-6, abs=0.0), c_name


def test_two_runs_give_byte_identical_files(tmp_path):
    (tmp_path / "a").mkdir()
    (tmp_path / "b").mkdir()
    for path_a, path_b in zip(run_export(tmp_path / "a"), run_export(tmp_path / "b")):
        assert path_a.read_bytes() == path_b.read_bytes(), path_a.name


def test_c_literals():
    assert export_params.c_literal(40.0) == "EKF_R(4.000000e+01)"
    assert export_params.c_literal(0.07) == "EKF_R(7.000000e-02)"
    assert export_params.c_literal(-20) == "EKF_R(-2.000000e+01)"
    assert export_params.c_literal(1.234567890123) == "EKF_R(1.234568e+00)"  # 7 significant digits
    assert export_params.c_literal(0.00001234567) == "EKF_R(1.234567e-05)"
    assert export_params.c_literal(0.0) == "EKF_R(0.000000e+00)"
    for bad in (math.nan, math.inf, -math.inf):
        with pytest.raises(ValueError):
            export_params.c_literal(bad)


def test_axes_that_are_not_the_project_grids_are_refused(tmp_path):
    params = synthetic_params()
    params.t_grid[-1] = -21.0
    with pytest.raises(ValueError, match="project grids"):
        export_params.write_c_files(params, tmp_path / "a.c", tmp_path / "a.h")


# --- results/s1/params.md ---------------------------------------------------------------------------


def section(text, heading):
    """Return the lines under `heading` (a whole heading line) up to the next heading of any level."""
    return re.split(r"\n#", text.split(heading + "\n")[1])[0].split("\n")


def table_rows(lines):
    """Return the cells of every markdown table row that starts with a number."""
    return [[cell.strip() for cell in line.strip("|").split("|")] for line in lines if re.match(r"\| -?\d", line)]


def level_frame(*overrides):
    """A fit_levels.csv table of the columns params.md uses: one 25 degC level per override of this default fit."""
    default = {"T_degC": 25.0, "level": 1, "soc_pulses": 1.0, "R0_ohm": 0.02, "R1_ohm": 0.01, "tau1_s": 3.0,
               "rmse_fast_mV": 1.0, "n_pulses_used": 4, "soc_rest": 0.9, "R2_ohm": 0.015, "tau2_s": 300.0,
               "rmse_slow_mV": 0.5}
    return pd.DataFrame([{**default, **override} for override in overrides])


def test_md_has_the_ocv_valid_range_per_temperature(tmp_path):
    md_path, _, _ = run_export(tmp_path)
    text = md_path.read_text()

    # The synthetic OCV is held below SoC_MIN, so it first changes at the first grid point at or above it:
    # 0.0327 -> 0.04, 0.0 -> 0 (nothing held), 0.0474 -> 0.05, 0.0655 -> 0.07, 0.0781 -> 0.08, 0.1028 -> 0.11.
    assert table_rows(section(text, "## OCV")) == [
        ["40", "4.0", "4"], ["25", "0.0", "0"], ["10", "5.0", "5"], ["0", "7.0", "7"], ["-10", "8.0", "8"],
        ["-20", "11.0", "11"],
    ]  # fmt: skip
    assert "OCV fallback (the 25 degC curve used at every temperature): no." in text


def test_md_flags_the_ocv_fallback(tmp_path):
    md_path, _, _ = run_export(tmp_path, fallback=True)
    text = md_path.read_text()
    assert "OCV fallback (the 25 degC curve used at every temperature): yes." in text
    # With the 25 degC curve everywhere, every temperature is valid from 0.
    assert {tuple(row[1:]) for row in table_rows(section(text, "## OCV"))} == {("0.0", "0")}


def test_md_has_the_ocv_correction_table_with_one_row_per_rest_point(tmp_path):
    md_path, _, _ = run_export(tmp_path)
    rows = table_rows(section(md_path.read_text(), "## OCV correction from the HPPC rest voltages"))
    assert len(rows) == 3 * len(T_GRID_DEGC)
    assert rows[:3] == [["40", "100", "4.21", "4.2", "10"], ["40", "50", "3.87", "3.85", "20"],
                        ["40", "10", "3.63", "3.57", "60"]]
    assert [row[0] for row in rows[-3:]] == ["-20"] * 3


def test_md_has_one_pair_of_tables_per_temperature_with_c_equal_tau_over_r(tmp_path):
    md_path, _, _ = run_export(tmp_path)
    text = md_path.read_text()

    for temp in T_GRID_DEGC:
        assert f"### {temp} degC\n" in text
    assert text.count("Fast branch (RC 1):") == 6
    assert text.count("Slow branch (RC 2):") == 6
    assert "| level | SoC (%) | R0 (mOhm) | R1 (mOhm) | tau1 (s) | C1 (F) | RMSE (mV) | pulses used |" in text
    assert "| level | SoC (%) | R2 (mOhm) | tau2 (s) | C2 (F) | RMSE (mV) |" in text

    # 25 degC, level 1: cold = 0, so R1 = 0.01 Ohm, tau1 = 3 s, C1 = 300 F; R2 = 0.015 Ohm, tau2 = 300 s, C2 = 20000 F.
    fast, slow = [row for row in table_rows(section(text, "### 25 degC")) if row[0] == "1"]
    assert fast == ["1", "100", "20", "10", "3", "300", "1.2", "4"]
    assert slow == ["1", "91", "15", "300", "20000", "0.8"]


def test_md_shows_n_a_for_missing_values_and_ignores_flag_columns(tmp_path):
    md_path, _, _ = run_export(tmp_path)
    text = md_path.read_text()

    # The last level of 25 degC (level 12) has no R2, tau2, SoC or RMSE for the slow branch.
    slow_last = [row for row in table_rows(section(text, "### 25 degC")) if row[0] == "12"][1]
    assert slow_last == ["12", "n/a", "n/a", "n/a", "n/a", "n/a"]

    # The failed fast fit of -20 degC level 1 shows n/a in R0, R1, tau1, C1 and RMSE, and 0 pulses used.
    fast_first = table_rows(section(text, "### -20 degC"))[0]
    assert fast_first == ["1", "100", "n/a", "n/a", "n/a", "n/a", "n/a", "0"]

    # The flag columns of fit_levels.csv are not shown.
    assert "_ok" not in text and "True" not in text
    assert "nan" not in text.lower().replace("n/a", "")


def test_levels_are_listed_in_level_order():
    rows = table_rows(export_params.level_fit_lines(level_frame({"level": 2}, {"level": 1}), [25.0]))
    assert [row[0] for row in rows] == ["1", "2", "1", "2"]  # fast table, then slow table


def test_md_prints_n_a_for_c_when_a_resistance_is_zero():
    # A fit that ends at the bound has R = 0; C = tau / R must not stop the export.
    fast, slow = table_rows(export_params.level_fit_lines(level_frame({"R1_ohm": 0.0, "R2_ohm": 0.0}), [25.0]))
    assert fast == ["1", "100", "20", "0", "3", "n/a", "1", "4"]
    assert slow == ["1", "90", "0", "300", "n/a", "0.5"]


def test_outputs_do_not_name_the_private_spec_file(tmp_path):
    md_path, c_path, h_path = run_export(tmp_path)
    for path in (md_path, c_path, h_path, export_params.__file__):
        assert "PR" + "D" not in open(path).read(), path
